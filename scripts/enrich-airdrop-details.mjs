import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { AIRDROPS, IMPORT_META } from '../src/data/airdrops.generated.js';
import { parseAirdropDetail } from './airdrop-detail-parser.mjs';

const OUTPUT_FILE = fileURLToPath(new URL('../src/data/airdrops.generated.js', import.meta.url));
const CONCURRENCY = 2;
const REQUEST_GAP_MS = 900;
const MAX_ATTEMPTS = 7;

const wait = (milliseconds) => new Promise((resolve) => setTimeout(resolve, milliseconds));

async function fetchDetail(item) {
  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt += 1) {
    const response = await fetch(item.sourceUrl, {
      headers: { 'user-agent': 'Mozilla/5.0 TopCryptoAirdropsResearch/1.0' },
    });

    if (response.ok) {
      const detail = parseAirdropDetail(await response.text());
      if (!detail.campaignUrl || !detail.claimSteps.length) {
        throw new Error(`Missing detail fields for ${item.slug}`);
      }
      await wait(REQUEST_GAP_MS);
      return { ...item, ...detail };
    }

    if (response.status !== 429 && response.status < 500) {
      throw new Error(`HTTP ${response.status} for ${item.slug}`);
    }

    const retryAfter = Number(response.headers.get('retry-after'));
    const delay = Number.isFinite(retryAfter) && retryAfter > 0
      ? retryAfter * 1000
      : Math.min(3000 * 2 ** (attempt - 1), 45000);
    await wait(delay + Math.floor(Math.random() * 750));
  }

  throw new Error(`Retry limit reached for ${item.slug}`);
}

const enriched = new Array(AIRDROPS.length);
const failures = [];
let cursor = 0;
let completed = 0;

async function worker() {
  while (true) {
    const index = cursor;
    cursor += 1;
    if (index >= AIRDROPS.length) return;
    const item = AIRDROPS[index];
    try {
      enriched[index] = await fetchDetail(item);
    } catch (error) {
      failures.push({ index, item, error });
    }
    completed += 1;
    if (completed % 10 === 0 || completed === AIRDROPS.length) {
      console.log(`Enriched ${completed}/${AIRDROPS.length}`);
    }
  }
}

await Promise.all(Array.from({ length: CONCURRENCY }, () => worker()));

for (const failure of failures) {
  console.log(`Retrying ${failure.item.slug} sequentially`);
  enriched[failure.index] = await fetchDetail(failure.item);
}

const detailsCapturedAt = new Date().toISOString();
const meta = { ...IMPORT_META, detailsCapturedAt };
const output = `// Generated by scripts/import-airdrops.mjs and enriched on ${detailsCapturedAt}\nexport const IMPORT_META = ${JSON.stringify(meta, null, 2)};\n\nexport const AIRDROPS = ${JSON.stringify(enriched, null, 2)};\n`;
await writeFile(OUTPUT_FILE, output, 'utf8');
console.log(`Wrote ${enriched.length} enriched records to ${OUTPUT_FILE}`);
