import { mkdir, rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const SOURCE_PAGE = 'https://airdropalert.com/browse-airdrops/?category=featured';
const AJAX_URL = 'https://airdropalert.com/wp-admin/admin-ajax.php';
const PAGE_COUNT = 24;
const EXPECTED_TOTAL = 286;
const OUTPUT = resolve('src/data/airdrops.generated.js');

const htmlEntities = {
  '&amp;': '&', '&quot;': '"', '&#039;': "'", '&#39;': "'", '&lt;': '<', '&gt;': '>',
  '&nbsp;': ' ', '&hellip;': '...', '&ndash;': '-', '&mdash;': '-',
};

function decodeHtml(value = '') {
  return value
    .replace(/&#(x[0-9a-f]+|[0-9]+);/gi, (_, code) => String.fromCodePoint(code.toLowerCase().startsWith('x') ? parseInt(code.slice(1), 16) : Number(code)))
    .replace(/&[a-z#0-9]+;/gi, (entity) => htmlEntities[entity] ?? entity);
}

function clean(value = '') {
  return decodeHtml(value.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim());
}

function matchOne(html, expression) {
  return html.match(expression)?.[1] ?? '';
}

function parseCard(cardHtml, page, capturedAt) {
  const sourceUrl = matchOne(cardHtml, /data-href="([^"]+)"/);
  const name = clean(matchOne(cardHtml, /<h4 class="title">([\s\S]*?)<\/h4>/));
  const logoUrl = matchOne(cardHtml, /<div class="logo">[\s\S]*?<img[^>]+src="([^"]+)"/);
  const ribbon = matchOne(cardHtml, /data-ribbon=(?:"([^"]+)"|([^\s>]+))/) || matchOne(cardHtml, /aidrop-label-([a-z-]+)/);
  const blockchain = clean(matchOne(cardHtml, /class="blockchain-logo" tooltip="([^"]+)"/)) || 'Other';
  const requirements = [...cardHtml.matchAll(/tooltip="([^"]+)"\s+class="social-item"/g)].map((match) => clean(match[1])).filter(Boolean);
  const values = [...cardHtml.matchAll(/<div class="value">[\s\S]*?<div class="amount">([\s\S]*?)<\/div>[\s\S]*?<div class="approx">([\s\S]*?)<\/div>[\s\S]*?<\/div>/g)]
    .map((match) => ({ amount: clean(match[1]), approx: clean(match[2]) }))
    .filter((item) => item.amount || item.approx);
  if (!sourceUrl || !/^https:\/\/airdropalert\.com\/airdrops\//.test(sourceUrl)) return null;
  const sourcePath = new URL(sourceUrl).pathname.split('/').filter(Boolean).at(-1) ?? '';
  const slug = sourcePath.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  if (!name || !slug) return null;
  return { name, slug, sourceUrl, sourcePage: page, ribbon, blockchain, logoUrl, requirements, values, capturedAt, quality: name && blockchain && values.length ? 'ready' : 'needs-review' };
}

async function request(url, options = {}) {
  const response = await fetch(url, options);
  if (!response.ok) throw new Error(`Request failed (${response.status}) for ${url}`);
  return response.text();
}

async function main() {
  const capturedAt = new Date().toISOString();
  const sourceHtml = await request(SOURCE_PAGE);
  const nonce = matchOne(sourceHtml, /_wpnonce=([a-z0-9]+)/i);
  if (!nonce) throw new Error('Could not find the source AJAX nonce');

  const records = [];
  for (let page = 1; page <= PAGE_COUNT; page += 1) {
    const body = new URLSearchParams({ action: 'fetch_airdrops', kyc: '', status: 'open', category: 'featured', blockchain: '', sort: 'newest', search_query: '', paged: String(page), _wpnonce: nonce });
    const response = await request(AJAX_URL, { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' }, body });
    const cards = response.match(/<div class="row card card-item[\s\S]*?(?=<div class="row card card-item|<div class=['"]airdrop-pagination|<\/div>\s*$)/g) ?? [];
    if (!cards.length) throw new Error(`Page ${page} returned no cards`);
    for (const card of cards) {
      const parsed = parseCard(card, page, capturedAt);
      if (parsed) records.push(parsed);
    }
  }

  const unique = [...new Map(records.map((record) => [record.sourceUrl, record])).values()];
  if (unique.length !== EXPECTED_TOTAL) throw new Error(`Expected ${EXPECTED_TOTAL} unique records, received ${unique.length}`);
  if (new Set(unique.map((record) => record.slug)).size !== unique.length) throw new Error('Duplicate local slug detected');

  const output = `// Generated by scripts/import-airdrops.mjs on ${capturedAt}\nexport const IMPORT_META = ${JSON.stringify({ capturedAt, source: SOURCE_PAGE, status: 'open', category: 'featured', sort: 'newest', pages: PAGE_COUNT, total: unique.length }, null, 2)};\n\nexport const AIRDROPS = ${JSON.stringify(unique, null, 2)};\n`;
  await mkdir(dirname(OUTPUT), { recursive: true });
  const temporary = `${OUTPUT}.tmp`;
  await writeFile(temporary, output, 'utf8');
  await rename(temporary, OUTPUT);
  console.log(`Imported ${unique.length} records from ${PAGE_COUNT} pages into ${OUTPUT}`);
}

main().catch((error) => { console.error(error.message); process.exitCode = 1; });
